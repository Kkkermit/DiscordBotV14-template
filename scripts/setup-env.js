'use strict';

/**
 * Interactive helper that creates the `.env` file.
 *
 *   npm run setup
 *
 * Every answer is validated with the same rules the bot uses on startup.
 */

const fs = require('node:fs');
const path = require('node:path');
const readline = require('node:readline');
const { ENV_FILE_PATH, EnvValidationError, parseEnv } = require('../src/env');
const { logger } = require('../src/lib/logger');

const log = logger.child('Setup');

/**
 * The questions asked, in order. `key` is the variable name written to `.env`.
 * @type {{ key: string, question: string, required: boolean }[]}
 */
const FIELDS = [
	{ key: 'DISCORD_TOKEN', question: 'Bot token (Developer Portal → Bot → Reset Token)', required: true },
	{ key: 'DISCORD_GUILD_ID', question: 'Development server ID, for instant command updates', required: false },
	{ key: 'DEVELOPER_IDS', question: 'Your Discord user ID(s), comma-separated', required: false },
	{ key: 'MONGODB_URI', question: 'MongoDB connection string', required: false },
];

/**
 * Formats a value for a `.env` file, quoting it when it contains characters with a special meaning.
 * The `.env` format has no escape sequences, so the first quote character not in the value is used.
 * Double quotes come last because they turn `\n` into a line break.
 *
 * @param {string} value
 * @returns {string}
 */
function formatEnvValue(value) {
	if (!/[\s#"'`]/.test(value)) return value;
	const quote = ["'", '`', '"'].find((candidate) => !value.includes(candidate));
	if (!quote) throw new Error('A value cannot contain single quotes, double quotes and backticks at once.');
	return `${quote}${value}${quote}`;
}

/** @param {Record<string, string>} values */
function buildEnvFile(values) {
	const lines = [
		'# Generated by "npm run setup". See .env.example for a description of every variable.',
		'# Keep this file private: anyone with your token can control your bot.',
		...FIELDS.map(({ key }) => `${key}=${formatEnvValue(values[key] ?? '')}`),
		'LOG_LEVEL=info',
	];
	return `${lines.join('\n')}\n`;
}

/**
 * Returns the validation problem for a single variable, or `null` if the value is valid.
 * Uses the bot's own validator with a placeholder token so only the asked field is checked.
 *
 * @param {string} key
 * @param {string} value
 * @returns {string | null}
 */
function validateField(key, value) {
	try {
		parseEnv({ DISCORD_TOKEN: 'placeholder', [key]: value });
		return null;
	} catch (error) {
		if (error instanceof EnvValidationError) return error.issues.join(' ');
		throw error;
	}
}

/** Thrown when stdin closes before every question was answered. */
class InputEndedError extends Error {}

/**
 * Creates a prompt function that reads one line per question.
 * Lines are buffered by the async iterator, so answers piped in all at once are not lost.
 *
 * @param {import('node:readline').Interface} rl
 * @returns {(question: string) => Promise<string>}
 */
function createPrompt(rl) {
	const lines = rl[Symbol.asyncIterator]();
	return async (question) => {
		rl.setPrompt(question);
		rl.prompt();
		const { value, done } = await lines.next();
		if (done) throw new InputEndedError('Input ended before setup was finished, nothing was written.');
		return value.trim();
	};
}

/**
 * Asks one question until the answer is valid. Optional questions accept an empty answer.
 *
 * @param {(question: string) => Promise<string>} ask
 * @param {typeof FIELDS[number]} field
 */
async function askField(ask, { key, question, required }) {
	while (true) {
		const answer = await ask(`${question} ${required ? '(required)' : '(optional)'}: `);
		if (!answer && !required) return '';

		const problem = answer ? validateField(key, answer) : `${key} is required.`;
		if (!problem) return answer;
		log.error(problem);
	}
}

async function main() {
	const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
	// Ctrl+C while a question is open: leave without writing anything.
	rl.on('SIGINT', () => {
		rl.close();
		process.stdout.write('\n');
		log.warn('Setup cancelled, nothing was written.');
		process.exit(130);
	});
	const ask = createPrompt(rl);

	try {
		const relativePath = path.relative(process.cwd(), ENV_FILE_PATH) || '.env';
		if (fs.existsSync(ENV_FILE_PATH)) {
			const answer = await ask(`${relativePath} already exists. Overwrite it? (y/N) `);
			if (!/^y(es)?$/i.test(answer)) {
				log.info('Kept your existing .env file.');
				return;
			}
		}

		log.info('Answer the questions below. Press Enter to skip optional ones.');
		/** @type {Record<string, string>} */
		const values = {};
		for (const field of FIELDS) {
			values[field.key] = await askField(ask, field);
		}

		fs.writeFileSync(ENV_FILE_PATH, buildEnvFile(values));
		// Only your user may read the file. (Has no effect on Windows, which uses its own permissions.)
		fs.chmodSync(ENV_FILE_PATH, 0o600);
		log.success(`Saved ${relativePath}. Start the bot with "npm start".`);
	} finally {
		rl.close();
	}
}

if (require.main === module) {
	main().catch((error) => {
		if (error instanceof InputEndedError) log.error(error.message);
		else log.error('Setup failed:', error);
		process.exitCode = 1;
	});
}

module.exports = { formatEnvValue, buildEnvFile, validateField };
